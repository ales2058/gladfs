#pragma once
// ============================================================================
//  GladFS — учебная файловая система (ТулГУ, лабораторная работа)
//
//  Здесь собраны ВСЕ числовые константы проекта. В остальном коде
//  «волшебных чисел» нет: любой размер или служебное значение имеет имя.
// ============================================================================

#include <cstdint>

namespace gladfs {

// ---------------------------------------------------------------------------
// Геометрия диска
// ---------------------------------------------------------------------------
constexpr uint32_t BLOCK_SIZE   = 512;   // размер блока (равен сектору дискеты)
constexpr uint32_t TOTAL_BLOCKS = 2048;  // всего блоков => диск 1 МиБ

// ---------------------------------------------------------------------------
// Раскладка образа: какие блоки занимает каждая служебная структура
// ---------------------------------------------------------------------------
constexpr uint32_t SUPERBLOCK_NO = 0;    // блок 0            — суперблок
constexpr uint32_t FAT_FIRST     = 1;    // блоки 1..8        — таблица FAT
constexpr uint32_t FAT_BLOCKS    = 8;    // 2048 записей * 2 байта = 4096 байт
constexpr uint32_t ROOT_FIRST    = 9;    // блоки 9..24       — корневой каталог
constexpr uint32_t ROOT_BLOCKS   = 16;
constexpr uint32_t DATA_FIRST    = 25;   // блоки 25..2047    — данные файлов
constexpr uint32_t DATA_BLOCKS   = TOTAL_BLOCKS - DATA_FIRST;   // 2023

// Каталог: 128 записей по 64 байта (16 блоков * 512 байт / 64 байта)
constexpr uint32_t DIRENTRY_SIZE  = 64;
constexpr uint32_t ROOT_ENTRIES   = ROOT_BLOCKS * BLOCK_SIZE / DIRENTRY_SIZE;

// ---------------------------------------------------------------------------
// Значения записей FAT (одна запись uint16_t на каждый блок диска)
// ---------------------------------------------------------------------------
constexpr uint16_t FAT_FREE     = 0x0000;  // блок свободен
constexpr uint16_t FAT_EOF      = 0xFFFF;  // последний блок цепочки файла
constexpr uint16_t FAT_RESERVED = 0xFFFE;  // служебный блок (суперблок/FAT/каталог)

// ---------------------------------------------------------------------------
// Ограничения имён
// ---------------------------------------------------------------------------
constexpr unsigned NAME_MAX         = 23;  // максимум символов в имени файла
constexpr unsigned VOLUME_NAME_MAX  = 15;  // максимум символов в имени тома

// ---------------------------------------------------------------------------
// Атрибуты файла (битовая маска) и флаги записи каталога
// ---------------------------------------------------------------------------
constexpr uint8_t ATTR_READONLY = 0x01;
constexpr uint8_t ATTR_HIDDEN   = 0x02;
constexpr uint8_t ATTR_SYSTEM   = 0x04;
constexpr uint8_t ATTR_TRASHED  = 0x08;    // файл в корзине
constexpr uint8_t ATTR_DIRECTORY = 0x10;   // запись является каталогом
                                           // (каталог — файл, содержимое которого
                                           //  — массив таких же записей DirEntry)

// Ограничения дерева каталогов (защита от зацикливания при повреждениях)
constexpr unsigned MAX_DIR_DEPTH = 32;

constexpr uint8_t ENTRY_USED = 0x01;       // запись каталога занята файлом

// ---------------------------------------------------------------------------
// Права доступа: старший полубайт — права владельца, младший — всех остальных
// (как chmod: r=4, w=2, x=1; пример: 0x64 = rw- для владельца, r-- для остальных)
// ---------------------------------------------------------------------------
constexpr uint8_t PERM_READ  = 4;
constexpr uint8_t PERM_WRITE = 2;
constexpr uint8_t PERM_EXEC  = 1;
constexpr uint8_t PERM_OWNER_SHIFT = 4;
constexpr uint8_t DEFAULT_PERMS = 0x64;    // новый файл: rw- / r--

// ---------------------------------------------------------------------------
// Пользователи (таблица хранится в скрытом системном файле внутри ФС)
// ---------------------------------------------------------------------------
constexpr unsigned NAME_MAX_USERS = 23;    // макс. длина имени пользователя
constexpr unsigned MAX_USERS      = 32;    // макс. число пользователей
constexpr char     USERS_FILE_NAME[] = "_users";

// Флаги записи пользователя
constexpr uint8_t USER_USED  = 0x01;
constexpr uint8_t USER_ADMIN = 0x02;

// Итерации функции вывода ключа из пароля (KDF)
constexpr uint32_t KDF_ITERATIONS_VOLUME = 2048;  // ключ шифрования тома
constexpr uint32_t KDF_ITERATIONS_USER   = 1024;  // хеши паролей пользователей

// Флаги шифрования в суперблоке
constexpr uint8_t CRYPTO_ENABLED = 0x01;

// ---------------------------------------------------------------------------
// Служебные константы формата
// ---------------------------------------------------------------------------
constexpr uint16_t FORMAT_VERSION = 3;
constexpr char     SIGNATURE[8]   = {'G', 'L', 'A', 'D', 'F', 'S', '1', '\0'};

// Проверки того, что константы согласованы между собой (ловится на компиляции)
static_assert(TOTAL_BLOCKS * sizeof(uint16_t) == FAT_BLOCKS * BLOCK_SIZE,
              "FAT должна занимать ровно FAT_BLOCKS блоков");
static_assert(ROOT_BLOCKS * BLOCK_SIZE == ROOT_ENTRIES * DIRENTRY_SIZE,
              "каталог должен занимать ровно ROOT_BLOCKS блоков");

}  // namespace gladfs
